session_start();

require_once "db.php";

/*
|--------------------------------------------------------------------------
| Check Login
|--------------------------------------------------------------------------
*/

if (!isset($_SESSION["user_id"])) {

    header("Location: inex.php");

    exit();

}

/*
|--------------------------------------------------------------------------
| Load Current User
|--------------------------------------------------------------------------
*/

$stmt = $db->prepare("

SELECT

    id,
    username,
    created_at

FROM users

WHERE id = ?

LIMIT 1

");

$stmt->execute([

    $_SESSION["user_id"]

]);

$user = $stmt->fetch();

/*
|--------------------------------------------------------------------------
| Invalid Session
|--------------------------------------------------------------------------
*/

if (!$user) {

    session_destroy();

    header("Location: login.php");

    exit();

}

/*
|--------------------------------------------------------------------------
